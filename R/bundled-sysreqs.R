bundled_supported_managers <- c("apt", "dnf", "yum", "zypper", "apk")

bundled_name_set <- function(package_manager) {
  if (identical(package_manager, "yum")) "dnf" else package_manager
}

bundled_sysreqs <- function(packages, platform, repo = "cran", error = NULL) {
  pm <- platform$package_manager
  if (!is.character(pm) || length(pm) != 1L || is.na(pm) ||
        !pm %in% bundled_supported_managers) {
    if (!is.null(error)) {
      stop(error)
    }
    stop(
      "Bundled fallback data currently supports apt, dnf, yum, zypper, ",
      "and apk platforms only.",
      call. = FALSE
    )
  }
  name_set <- bundled_name_set(pm)

  packages <- compact_chr(packages)
  known <- unique(bundled_sysreqs_db$r_package)
  data <- bundled_sysreqs_db[
    bundled_sysreqs_db$r_package %in% packages &
      bundled_sysreqs_db$package_manager == name_set, ,
    drop = FALSE
  ]
  # Packages absent from the table entirely, plus packages the table knows
  # for other package managers but has no name for on this one (for example
  # V8 on zypper or apk).
  unresolved <- c(
    setdiff(packages, known),
    setdiff(intersect(packages, known), unique(data$r_package))
  )

  if (!nrow(data)) {
    if (!is.null(error)) {
      stop(error)
    }
    plan <- new_sysreqr_plan(platform_info = platform, backend = "bundled")
    attr(plan, "unresolved") <- unresolved
    return(plan)
  }

  data$sysreq <- NA_character_
  data$install_script <- vapply(
    data$system_package,
    install_script_for_package,
    character(1),
    platform = platform
  )
  data$pre_install <- NA_character_
  data$post_install <- NA_character_
  data$platform <- paste0(platform$distro, "-", platform$version)
  data$package_manager <- pm
  data$installed <- NA
  data$source <- "bundled"
  data$confidence <- "medium"
  data$notes <- paste0(
    "Requirement from bundled sysreqR fallback data for repository `",
    repo,
    "`.",
    if (!identical(name_set, "apt")) {
      paste0(
        " Name from the bundled ", name_set,
        " set; verify the exact name on your distribution."
      )
    } else {
      ""
    }
  )

  plan <- new_sysreqr_plan(
    data,
    platform_info = platform,
    backend = "bundled"
  )
  attr(plan, "unresolved") <- unresolved
  plan
}

bundled_has_packages <- function(packages) {
  all(compact_chr(packages) %in% bundled_sysreqs_db$r_package)
}
